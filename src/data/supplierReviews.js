/**
 * Synchronous getter for supplier review data
 */
export function getSupplierRatingData(shopId, baseRating) {
  if (MOCK_SUPPLIER_REVIEWS[shopId]) {
    return MOCK_SUPPLIER_REVIEWS[shopId];
  }
  return generateFallbackReview(shopId, baseRating);
}

/**
 * Asynchronous simulated API call to fetch supplier rating & recent review
 * Simulates a realistic 120ms network latency
 */
export async function fetchSupplierRatingData(shopId, baseRating) {
  return new Promise((resolve) => {
    setTimeout(() => {
      const data = getSupplierRatingData(shopId, baseRating);
      resolve(data);
    }, 120);
  });
}
